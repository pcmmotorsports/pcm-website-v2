-- ── 鎖的上限 ────────────────────────────────────────────────────────────────
--    `ADD COLUMN` 會對 `orders` 取 ACCESS EXCLUSIVE;FK 會對 `coupons` 取 SHARE ROW EXCLUSIVE。
--    沒有上限的話它會**無限等**。
