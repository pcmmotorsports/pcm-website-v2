--    **還在【等】的時候它還沒拿到鎖 ⇒ 既有的讀取照常跑。**真正的傷害是排隊:
--    那個等待中的 ALTER 卡在鎖佇列前面 ⇒ **它後面新來的查詢全部排在它後面**
--    ⇒ 結帳與後台是被【佇列】停住的, 不是被鎖本身。
--    📌 差別有用:看到卡住時要去看 `pg_locks` 的**佇列**, 不是問「誰持有鎖」。
--    `lock_timeout` 管等鎖;`statement_timeout` 管拿到鎖之後跑太久。兩個都設。
