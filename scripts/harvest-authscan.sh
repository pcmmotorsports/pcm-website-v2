#!/bin/sh
# harvest-authscan.sh —— 收割前授權掃描:被收的 commit body 裡,作者有沒有自陳「這件事我還沒拿到授權」。
#
# ══════════════════════════════════════════════════════════════════════════
# 🔴 射程(先讀這一段,不然你會把它讀成一道它做不到的保證)
# ══════════════════════════════════════════════════════════════════════════
# ① **它命中的是【字面】,不是【授權狀態】** ⇒ 假陽性會一直有。
#    實例(2026-08-18 首跑五批,兩筆命中,兩筆都判「可留」):
#      · 「與主視窗核可草案的偏離」—— 偏離的對象是同儕的草案,不是 Sean 的拍板
#      · 「max-rows 修法 plan …等 Sean 批」—— 講的是【那份 plan 的狀態】,不是這顆做了沒授權的事
#    ⇒ 🔴 **它的價值在【逼人開檔看】,不在它的判定。不得自動化成「命中就拒收」。**
#
# ② 🔴🔴 **反方向的漏:作者【沒寫】那幾個字的未授權改動,它一個都抓不到。**
#    它守的是「**誠實作者的自陳**」,不是「未授權的改動」——**這兩件事不一樣。**
#    ⇒ 「掃過、零命中」**不等於**「授權沒問題」。
#      (這正是 memory `feedback_absence-read-as-verified` 的形狀:
#       什麼都沒有 → 被讀成 → 檢查過了。)
#
# ③ ⚠️ **②那半目前沒有機制**,只能靠 code review 與作者自律。
#    本檔**不是**一道覆蓋完整的閘,不要在報告裡讓它看起來像。
#
# 🔴 triage 判準(命中之後照這句判,不是照字面):
#    問的不是「commit body 有沒有那幾個字」,
#    是「**這顆 commit【做了】一件需要授權而還沒拿到的事嗎**」。
#    · 描述「某份文件在等批」= 沒做。
#    · 改了使用者看得到的東西而 Sean 沒點頭 = 做了 ⇒ 停,不要收。
#
# ══════════════════════════════════════════════════════════════════════════
# 🔴 兩個坑,寫的人(I 窗)第一版都踩了 —— 你會踩同樣的
# ══════════════════════════════════════════════════════════════════════════
# ① **範圍寫錯,而錯的樣子跟對的一樣**:merge 顆那一批 = `<merge>^1..<merge>^2`
#    (^1 = 舊 dev、^2 = 被併進來的界線)。第一版寫成 `<後來的 commit>..<merge>`,
#    那個範圍是**空的**,而 `grep` 對空輸入回零命中
#    ⇒ 印出來與「掃過而乾淨」**一模一樣** = 假通過。
#    ⇒ 本檔因此**先報批內顆數**,顆數 0 直接判「範圍算錯」,不判「乾淨」。
# ② **標籤無條件印**:`grep …; echo "(空 = 零命中)"` 在【有命中】時照樣印那句,
#    而它就印在命中的正下方。⇒ 本檔的每一句結論都由**結果**決定。
# ③ 🔴 **`git rev-parse <非 merge 顆>^2` 失敗時,仍然把【原字串】印到 stdout**
#    ⇒ 用 `$(git rev-parse "$M^2" 2>/dev/null || true)` 接的話,變數會拿到 `"<sha>^2"` 這個
#    **非空的垃圾值**,`[ -z "$P2" ]` 那道守衛**從來不會成立** ⇒ 一路掉到 grep,
#    分母變空字串、`[ "$N" = "0" ]` 也不成立 ⇒ **印出「✅ 零命中」而 rc=0。**
#    🔴 這是本檔自己在防的那個形狀,而本檔第一版就犯了它 —— 是負向對照(餵一顆非 merge)抓到的。
#    ⇒ 修法:`git rev-parse --verify --quiet`(失敗時**不印東西**、回非 0),
#      並且對 `$N` 加「不是純數字就當算錯」那道。
#
# 用法:
#   sh scripts/harvest-authscan.sh <merge-commit> [<merge-commit> ...]
#   rc: 0 = 全部零命中且範圍都算得出來 / 1 = 有命中或有範圍算錯 ⇒ 人去看
set -uo pipefail

PAT='偏離|未拍板|等 Sean|未批|他說乙|未經批准|尚未批准'

if [ "$#" -eq 0 ]; then
  echo "用法: sh scripts/harvest-authscan.sh <merge-commit> [<merge-commit> ...]" >&2
  exit 2
fi

rc=0
for M in "$@"; do
  # 🔴 --verify --quiet:失敗時不印東西、回非 0(見檔頭坑③)
  P1="$(git rev-parse --verify --quiet "$M^1")" || P1=""
  P2="$(git rev-parse --verify --quiet "$M^2")" || P2=""
  if [ -z "$P1" ] || [ -z "$P2" ]; then
    echo "== $M  ⚠️ 不是 merge 顆(取不到兩個 parent)⇒ 本掃描不適用。**這不是「乾淨」。**"
    rc=1
    continue
  fi
  N="$(git rev-list --count "$P1".."$P2" 2>/dev/null)" || N=""
  echo "== $M  批內 $N 顆(範圍 $M^1..$M^2)=="
  # 🔴 空字串與非數字都要當「算錯」,不能只擋 0 —— 空字串 `[ "$N" = "0" ]` 不成立,會一路掉到 grep
  case "$N" in
    ''|*[!0-9]*) echo "   🔴 算不出批內顆數 ⇒ **範圍算錯了**。這不是「乾淨」。"; rc=1; continue ;;
    0)           echo "   🔴 批內 0 顆 ⇒ **範圍算錯了**。這不是「乾淨」,是【沒掃到東西】。"; rc=1; continue ;;
  esac
  HITS="$(git log --format='%h %B' "$P1".."$P2" | grep -nE "$PAT" || true)"
  if [ -n "$HITS" ]; then
    printf '%s\n' "$HITS"
    echo "   🔴 有命中 ⇒ **開檔看那顆 commit 動了什麼**,照檔頭的 triage 判準判,不要照字面判。"
    rc=1
  else
    echo "   ✅ 零命中(分母 $N 顆;pattern: $PAT)"
    echo "      ⚠️ 零命中只證「作者沒有自陳」,不證「授權沒問題」——見檔頭射程②。"
  fi
done
exit $rc
