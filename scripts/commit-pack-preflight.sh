#!/usr/bin/env bash
# commit 包預檢 —— 在一棵【乾淨的 dev】上,只放這一包要收的檔,跑 typecheck + lint。
#
# 🔴 它殺的是哪一族病(分母是量出來的, 不是印象):
#      git log --oneline -60 | grep -cE "工作樹|沒進版控|躺在|CI 全紅|連紅"  ⇒ 4
#      負對照(同一把尺量一個不存在的字)                                     ⇒ 0   ← 尺是活的
#    而那四顆是連續的 HEAD~3..HEAD ⇒ 不是失手, 是結構性的洞。
#
# 🔴 機制:漏收一支【被其他收進去的檔需要】的檔
#      ⇒ 乾淨樹上少那一支 ⇒ typecheck 紅
#      ⇒ 而共用樹上它還在 ⇒ 本機永遠綠。**那正是那四顆的共同形狀。**
#
# ⚠️ 它【抓不到】什麼(必要不充分, 不要當成通過就沒事):
#      · 🔴 **少收一支【帶守門的】測試檔 ⇒ 它會【綠】, 只是綠得比較小聲**
#        2026-08-24 實測(補洞窗):退回一支帶守門的測試檔 ⇒ exit=0 綠,
#        而測試總數 177 -> 165 ⇒ **12 格守門安靜地消失了**
#        ⇒ 多了一支在等的檔 = 紅 = 會吵 = 有人會發現(本腳本抓得到)
#          少了一支帶守門的檔 = 綠 = 不吵 = 沒有人會發現(本腳本【看不到】)
#        ⇒ 固定動作(腳本做不到, 要人做):比對【Test Files / Tests 兩欄的格數】
#          基準 = 主樹上跑該片相關測試的兩欄;格數變少 ⇒ 漏收了帶守門的檔
#      · runtime-only 的相依
#      · **不驗你收的那些 hunk 對不對**(git add -p 的情況)
#        ⇒ 它驗的是「這一包自己站得住嗎」, 不是「這一包是不是你想要的」
#
# 用法:bash scripts/commit-pack-preflight.sh <repo 相對路徑>...
#      (餵絕對路徑也行 —— 開頭那段會正規化;不在【這棵工作樹】底下的絕對路徑直接 exit 2)
set -uo pipefail

[ "$#" -gt 0 ] || { echo "用法: bash $0 <repo 相對路徑>...(絕對路徑也行, 會被正規化)" >&2; exit 2; }

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
cd "$ROOT" || exit 1

# 🔴 2026-08-24 夜:把參數正規化成【repo 相對路徑】,再往下走。
#    病灶(線1 pcm-website-v2-3e 診斷、主視窗複現):下面 `cp "$f" "$W/$f"` 與最後
#    `( cd "$W" && npx vitest run $TESTS )` 都假設 $f 是相對的。餵絕對路徑時:
#      · cp 會建出 $W/Users/sean_1/... ⇒ 檔案根本沒進到它該在的位置
#      · vitest 在 $W 裡拿一個【指回主樹】的絕對路徑去跑 ⇒ workspace include 命中 0 支
#        ⇒ rc=1,而輸出是 "No test files found" ⇒ 本腳本印「站不住 ⇒ 多半漏收了一支」
#        —— 一個紅,而理由是錯的。
#    🔴 而【複製後 dirty 自檢】擋不住它:包內只有 1 支時,多出來的 `?? Users/` 也是 1
#       ⇒ 1 == 1 ⇒ 自檢通過,通過的理由是【錯的那個檔】。
#       ⚠️ ~~兩支以上才會被擋~~ **這句是假的, 而它是從【一次量測】推出來的通則**
#          (那一發沒錯:主視窗餵 3 支時真的量到 `複製後 dirty=1, 預期 3`;錯的是從它推出的通則)
#          審查 2026-08-24 實測:兩個絕對路徑落在【不同】頂層目錄時 porcelain 出 2 行、$#=2 ⇒ **通過**。
#          正確的話是:**只有當所有絕對路徑共用【同一個】untracked 頂層目錄時, 它才會被擋。**
#       ⇒ 這道自檢數的是【幾個】,而它要答的是【哪幾個】。
#    ⚠️ 而本檔檔頭與 CLAUDE.md 生態裡的範例對這個參數講的不是同一件事
#       (一處寫「具名路徑」、一處寫「完整路徑」)。
#       🔴 ~~兩邊都改成 repo 相對~~ **這句在寫下的當下就是假的** ——
#          `docs/phase-1-backlog.md` 那處仍寫「<完整路徑>...」且本次零改動(審查實查)。
#          ⇒ **本段的作用是【接住兩種寫法】, 不是統一它們。統一那件事欠著。**
_ARGS=()
for _f0 in "$@"; do
  # 🔴 審查 N2(第二輪):`$ROOT//scripts/x`(雙斜線 —— 拼路徑時很常見)⇒ 下面那個
  #    `${_f#"$ROOT"/}` 只吃掉一個斜線 ⇒ `_rel` 變成 **`/scripts/x`(還是絕對的)**
  #    ⇒ 它通過所有守門, 一路走到**建完 worktree** 才停在「來源不存在: /scripts/x」
  #    —— 又一個【理由錯的紅】, 而且這次還先付了建樹的錢。
  #    ⇒ 先把連續斜線壓成一個, 再往下判。
  _f=$(printf '%s' "$_f0" | tr -s '/')
  case "$_f" in
    "$ROOT")
      # 🔴 審查 N3:餵 repo 根目錄本身(沒有尾斜線)⇒ 舊版說「不在這棵工作樹底下」, 而它就在。
      #    一句假的錯誤訊息會叫人去找一個不存在的問題。
      echo "🔴 這是這棵工作樹的【根目錄】, 不是一支檔: $_f0" >&2; exit 2 ;;
    /*)
      _rel=${_f#"$ROOT"/}
      # ⚠️ 訊息講「這棵工作樹」不講「本 repo」—— 同一個 .git 底下的【別棵 worktree】
      #    也會走到這裡(審查實測:餵別棵樹的路徑會被拒), 而那時說「不在本 repo 底下」是假的,
      #    會讓人去找一個不存在的問題。
      [ "$_rel" != "$_f" ] || { echo "🔴 這個絕對路徑不在這棵工作樹底下(ROOT=$ROOT): $_f" >&2; exit 2; }
      ;;
    *) _rel=$_f ;;
  esac
  # 🔴 審查 F9:餵 `$ROOT/`(尾斜線 —— tab 補全很常見)⇒ `_rel` 變成空字串,
  #    它通過上面那道守門, 然後停在「來源不存在: 」—— **冒號後面是一片空白**,
  #    而那句話讀起來像「有一個檔不見了」。空參數要在這裡就吼掉。
  [ -n "$_rel" ] || { echo "🔴 這個參數正規化之後是空的(多半是尾斜線, 例如 \$ROOT/): $_f0" >&2; exit 2; }
  # 🔴 正規化之後**不得還是絕對路徑** —— 這是 N2 那條的兜底:
  #    上面壓斜線只治了已知的那一種寫法, 而這一格治的是「所有讓它還是絕對的寫法」。
  #    (判別句:治症狀的那行看得懂輸入長什麼樣, 這行不需要看得懂。)
  case "$_rel" in
    /*) echo "🔴 正規化之後仍是絕對路徑 ⇒ 它不在這棵工作樹底下(ROOT=$ROOT): $_f0" >&2; exit 2 ;;
  esac
  # 🔴 審查 N4:同一支檔同時餵【絕對】與【相對】⇒ 正規化後兩個一樣, 而 `$#` 是 2、porcelain 只有 1 行
  #    ⇒ 下面那道基準自檢會印「複製後 dirty=1, 預期 2 ⇒ 本次量測作廢」
  #    ⇒ 訊息會叫人去找【多出來的那個檔】, 而實際是**少了一個參數**。去重, 不要讓它走到那裡。
  _dup=0
  for _seen in ${_ARGS[@]+"${_ARGS[@]}"}; do [ "$_seen" = "$_rel" ] && { _dup=1; break; }; done
  [ "$_dup" -eq 1 ] && { echo "⚠️ 重複的參數(正規化後相同), 只算一次: $_f0"; continue; }
  _ARGS+=("$_rel")
done
# 🔴 審查 F10:macOS 內建 bash 3.2 在 `set -u` 之下, 空陣列展開 `"${_ARGS[@]}"` 會當成未綁定變數。
#    今天到不了(上面 `[ "$#" -gt 0 ]` 擋著, 而每個參數都會 push 一個元素),
#    而**有人日後在迴圈裡加一個 `continue` 就會崩**, 崩的樣子是 rc=127 —— 那與「閘擋了」分不出來。
#    ⇒ 用 `${_ARGS[@]+...}` 這個 3.2 也吃的寫法, 讓它在空的時候安靜展開成零個參數。
set -- ${_ARGS[@]+"${_ARGS[@]}"}
[ "$#" -gt 0 ] || { echo "🔴 正規化之後一個參數都不剩 ⇒ 沒有東西可以檢查(不得當成通過)" >&2; exit 2; }
W=$(mktemp -d "${TMPDIR:-/tmp}/pack-check.XXXXXX")/wt
trap 'git -C "$ROOT" worktree remove --force "$W" >/dev/null 2>&1; rm -rf "$(dirname "$W")"' EXIT

HEAD_SHA=$(git rev-parse --short HEAD)
echo "repo=$ROOT  HEAD=$HEAD_SHA  包內檔數=$#"

git worktree add --detach "$W" HEAD >/dev/null 2>&1 || { echo "🔴 建 worktree 失敗" >&2; exit 1; }

# 🔴 基準自檢:新樹必須是 0 dirty。不是就作廢 —— 髒的基準量出來的綠沒有意義。
BASE=$(git -C "$W" status --porcelain | wc -l | tr -d ' ')
if [ "$BASE" != "0" ]; then echo "🔴 新樹 dirty=$BASE(應為 0)⇒ 本次量測作廢" >&2; exit 1; fi

for f in "$@"; do
  [ -e "$f" ] || { echo "🔴 來源不存在: $f" >&2; exit 1; }
  mkdir -p "$W/$(dirname "$f")" && cp "$f" "$W/$f" || { echo "🔴 複製失敗: $f" >&2; exit 1; }
done

# 🔴 複製後自檢:dirty 必須【剛好等於】包內檔數。多了 = 我搬到別線的東西 ⇒ 那會讓結果偏綠。
GOT=$(git -C "$W" status --porcelain | wc -l | tr -d ' ')
if [ "$GOT" != "$#" ]; then
  echo "🔴 複製後 dirty=$GOT, 預期 $# ⇒ 本次量測作廢(多出來的會讓結果偏綠)" >&2
  git -C "$W" status --porcelain >&2
  exit 1
fi
echo "基準自檢: 建樹時 dirty=0 / 複製後 dirty=$GOT ✅"

# ════════════════════════════════════════════════════════════════════════════
# 🔴🔴 **漏收提示:主樹髒了、而【不在這一包裡】的檔(審查 2026-08-24 第二輪給的做法)**
# ----------------------------------------------------------------------------
# 上面那道基準自檢數的是【幾個】, 而「漏收了一支」這個問題要答的是【哪幾支】——
# 它結構上答不出來。本段不解決它, 但**指名得出候選**:
#   `page-measure.test.tsx` 那個假綠案例裡, 漏收的那支 CSS **正好就在這個差集裡**。
# ⚠️ **只印, 不 fail** —— 多窗夜跑時這棵樹會有別條線的髒檔, 拿它當判準會變成一道恆紅的閘
#    (而恆紅的閘與沒有閘等價, 見檔頭 `#884`)。
# ⚠️ **射程**:它只看得到「已經在工作樹裡髒著」的檔。真正漏收而**在別的分支/別棵 worktree**
#    的檔它看不到 ⇒ 差集是空的**不代表**這一包是完整的。
OUTSIDE=$(git -C "$ROOT" status --porcelain --untracked-files=all \
          | sed -e 's/^...//' -e 's/^.* -> //' \
          | while IFS= read -r _d; do
              [ -n "$_d" ] || continue
              _hit=0
              for _p in "$@"; do [ "$_p" = "$_d" ] && { _hit=1; break; }; done
              [ "$_hit" -eq 0 ] && printf '%s\n' "$_d"
            done)
OUT_N=$(printf '%s' "$OUTSIDE" | grep -c . || true)
if [ "${OUT_N:-0}" -gt 0 ]; then
  echo "⚠️ 主樹另有 $OUT_N 支髒檔【不在這一包裡】—— 漏收的話它會在這份清單裡:"
  printf '%s\n' "$OUTSIDE" | head -20 | sed 's/^/     · /'
  [ "$OUT_N" -gt 20 ] && echo "     …(只列前 20 支, 共 $OUT_N)"
  echo "   (這【不是】錯誤:多窗夜跑本來就會有別條線的髒檔。它是一份【候選名單】, 不是判準。)"
else
  echo "⚠️ 主樹沒有這一包以外的髒檔 —— 而這【不代表包是完整的】(見上面射程)。"
fi
# ════════════════════════════════════════════════════════════════════════════

( cd "$W" && pnpm install --frozen-lockfile >/dev/null 2>&1 ); IE=$?
( cd "$W" && TURBO_FORCE=1 pnpm typecheck > "$W/.tc.log" 2>&1 ); TE=$?
( cd "$W" && TURBO_FORCE=1 pnpm lint > "$W/.lint.log" 2>&1 ); LE=$?

echo "install=$IE  typecheck=$TE  lint=$LE"
[ "$TE" -eq 0 ] || { echo "--- typecheck 錯 ---"; grep -E "error TS" "$W/.tc.log" | head -20; }
[ "$LE" -eq 0 ] || { echo "--- lint 錯 ---"; tail -20 "$W/.lint.log"; }

# 🔴 包內若有測試檔, 在乾淨樹上跑一次 —— typecheck+lint 對「測試在等一支沒收的檔」零判別力。
# 2026-08-24 實錘:一包只放 design-tokens.test.ts ⇒ 本腳本原本印綠,
# 而同一個乾淨基準上跑 vitest ⇒ rc=1 / 15 格紅(新測試在等還沒 commit 的 globals.css)。
# 🔴 `*-browser.test.*` 那族**需要建置產物(`.next`)** —— 這句**仍然是真的**
#    (`orders-column-fit` / `orders-status-visibility` / `print-doc-cascade` 三支還在掃 `.next`)。
#    ~~在新 worktree 上必紅~~ / ~~那族在本工具下【零覆蓋】, 要另外在主樹跑~~
#    🔴🔴 **只有這兩句為假, 劃掉不刪(審查 F6 + 第二輪 Q5)。**
#    變的不是那個需求, 是**那個需求現在被滿足了**(下面先 build)⇒ 排除分支已拿掉, 那族會跑。
#    ⚠️ 第一輪我把整句都劃掉 —— 審查點名那會讓人以為「需要 .next」這件事消失了。**它沒有。**
#
#    📏 **「那族現在會跑」是量到的, 不是推的(2026-08-24 22:0x)**:
#       把 `apps/admin/src/components/orders/orders-column-fit-browser.test.tsx`
#       (那三支要掃 `.next` 的其中一支)加一行註解變髒 ⇒ 單獨成包跑本腳本 ⇒
#         `基準自檢 複製後 dirty=1 ✅ / install=0 typecheck=0 lint=0 build=0`
#         **`vitest(包內測試檔)=0  Test Files 1 passed (1)` ⇒ ✅ 站得住**
#       跑完立刻還原(`shasum` 前後相同、`porcelain=0`)。
#    🔴 **第一輪我寫「那族現在會跑」時, 手上只有一發【非 browser】的包** —— 審查逐字點名
#       「目前沒有任何一發乾淨樹量測撐著」。**它是對的, 而補量之後結論不變。**
#       兩件事分開記:**結論對** ≠ **當時有證據**。
#    ⚠️ 保留原理由(誤擋比漏抓更該修:一道會誤紅的收工閘會讓人繞過它 ⇒ 第五顆 `#884`)——
#       那個理由沒有被推翻, 被推翻的是**達成它的手段**(從「按檔名排除」換成「把需求滿足掉」)。
# 🔴🔴 先 build。**動機**是讓乾淨樹有 `.next`,
#    ~~【不是為了驗 build】~~ **這半句 2026-08-24 起為假(審查 F4 點名)**:
#    下面的通過條件裡有 `[ "$BE" -eq 0 ]` ⇒ **build 紅這一包就不算站得住** ⇒ 它就是在驗 build。
#    ⇒ 兩件事都是真的:動機是 `.next`,而**效果**是「build 也被納入判準」。兩句都要寫,不要只寫動機。
#
#    🔴 **審查同時提出「`.env*` 全 gitignore ⇒ 乾淨樹結構性缺 `apps/*/.env.local`
#       ⇒ build 可能因與包無關的原因紅 = 誤擋族」。那是【推出來的】,而我去量了:**
#    📏 2026-08-24 21:5x 實跑本腳本一支包(`scripts/migration-new-file-gate.test.ts`):
#       `install=0 typecheck=0 lint=0` → **`build=0`** → `vitest=0` ⇒ ✅ 站得住。
#       主樹確實有 `apps/admin/.env.local` 與 `apps/storefront/.env.local`,
#       `git check-ignore -v` ⇒ `.gitignore:94:.env*` ⇒ **乾淨樹確實沒有它們, 而 build 仍然過。**
#    ⇒ **那個誤擋今天【不成立】。** 它仍是一個真的結構性風險(哪天有 env 變成 build-time 必需就會發生),
#      而**在它發生之前不要拿它當理由改這道閘** —— 判別句:去跑一發, 看 `build=` 印什麼。
#    ⚠️ 同理審查的「這道閘會慢一個量級」:**也還沒發生。**
#       📏 兩發實測, 而**條件寫在數字旁邊**(§6-b 第 2 條:數字離開量測現場要帶著範圍走):
#         包=1 支、**無** browser 測試(`migration-new-file-gate.test.ts`)⇒ 全程 **≤ 60 秒**
#         包=1 支、**有** browser 測試(`orders-column-fit-browser.test.tsx`, 會 launch chromium
#           且掃 `.next`)                                                  ⇒ 全程 **≤ 60 秒**
#       兩發都含 install/typecheck/lint/build/vitest。
#       🔴 第一輪我只有前一發, 而審查指出「那個數字系統性低估的正是新納入的最壞情況」——
#          **那個擔憂是對的形狀**, 補量之後沒有發生。
#       ⇒ 要現值就自己跑一次計時, 不要引用這一行;包大小與有沒有 browser 測試都會改變它。
#    2026-08-24 兩次實測:一族測試在乾淨樹紅、在主樹全綠, 成因都是【缺建置產物】:
#      · `*-browser.test.tsx`(2 支) 主樹 ⇒ 2 passed / 9 tests / EXIT=0
#      · `page-measure.test.tsx`     它自己第一格就寫著「建置產物撈得到兩支 CSS」
#    🔴 我第一次是用【檔名】排除那族的 —— 而那族是由【它需要什麼】定義的, 不是由名字。
#       第二支就逃掉了(名字裡沒有 browser)⇒ 用字集追一個由需求定義的集合, 永遠慢一步。
#    ⇒ 改成把那個需求【滿足掉】, 而不是把不符合名字的排除掉。
( cd "$W" && TURBO_FORCE=1 pnpm build > "$W/.build.log" 2>&1 ); BE=$?
echo "build=$BE"
[ "$BE" -eq 0 ] || { echo "--- build 錯 ---"; tail -15 "$W/.build.log"; }

# 🔴 審查 F8:`SKIPPED_BROWSER` 在排除分支被拿掉之後**恆為 0** ⇒ 那句 `⚠️ 略過 N 支` 永遠印不出來。
#    死碼在守門裡特別貴:它讓人以為「有東西在盯著被略過的檔」。刪掉。
# 🔴 審查 F12:`TESTS="$TESTS $f"` + `npx vitest run $TESTS`(未引號)⇒ 檔名含空白就斷詞
#    ⇒ vitest 拿到兩個不存在的路徑 ⇒ rc=1 ⇒ 本腳本印「站不住 ⇒ 多半漏收了一支」
#    —— **又是一個理由錯的紅**(與本次修掉的絕對路徑那個同族)。⇒ 改用陣列。
TESTS=()
for f in "$@"; do
  case "$f" in
    *.test.ts|*.test.tsx) TESTS+=("$f");;
  esac
done
VE=0
if [ "${#TESTS[@]}" -gt 0 ]; then
  ( cd "$W" && npx vitest run "${TESTS[@]}" > "$W/.vt.log" 2>&1 ); VE=$?
  echo "vitest(包內測試檔)=$VE  $(grep -E 'Test Files' "$W/.vt.log" | tail -1)"
  [ "$VE" -eq 0 ] || { echo "--- vitest 錯 ---"; grep -E "FAIL|AssertionError" "$W/.vt.log" | head -10; }
else
  echo "vitest: 包內無測試檔 ⇒ 略過(而這【不是】一個綠, 是沒量)"
fi

# 🔴🔴 **審查 F1(2026-08-24):加了 build 之後, 有一族包從【假紅】變成【假綠】—— 而綠是被信任的那一邊。**
#    形狀:本工具跑的是「**HEAD 的整棵樹 + 你這包覆蓋上去的那幾支**」。
#    若包內某支測試斷言的是**建置產物的某個性質**, 而 **HEAD 本來就滿足那個性質**,
#    那麼**即使包裡漏收了那支「本來要造成該性質」的原始檔, 它照樣綠**。
#    實例(審查給的):包裡只放 `page-measure.test.tsx`(它第一格斷言「建置產物撈得到兩支 CSS」)
#    而**漏收它要驗的那支 CSS** ⇒ build 用 HEAD 的 CSS 產出兩支 ⇒ 測試綠 ⇒ 本腳本印 ✅。
#    ⚠️ **改動【前】同一包是紅的**(沒有 `.next` ⇒ 測試紅)⇒ 這一筆是**假紅換成假綠**。
#       那個假紅不是判別力, 它只是**剛好**指向同一個方向 —— 但它會被人讀成判別力。
#    🔴 **根治不在這裡**:承重的仍是上面那道「複製後 dirty 數」自檢, 而**它數的是【幾個】,
#       要答的是【哪幾支】** ⇒ 只要包外還有它需要的檔, 它就答不出來。
#       改成內容比對(比對【哪幾支】)是另一件事, 已排進線3 的隊。
#    ⇒ 在那之前, **這個 ✅ 的射程要寫在它旁邊, 不能只寫在檔頭** —— 檔頭會被跳過, 這一行不會。
#    🔴🔴 **第二輪審查點名:光是多印兩行字【不算修】** —— 逐字「印字是文件不是守門,
#       它一樣答不出哪幾支」。**它是對的。** ⇒ 已在基準自檢後面加一段
#       **「主樹髒了而不在這一包裡」的候選名單**(字面錨 `漏收提示`)——
#       `page-measure` 那個假綠案例裡漏收的那支 CSS **正好落在那個差集裡**。
#       ⚠️ 它仍**不是**根治(根治=內容比對), 而它與這兩行字的差別是:
#          **它指名得出候選, 這兩行只說得出「我答不出來」。**
if [ "$IE" -eq 0 ] && [ "$TE" -eq 0 ] && [ "$LE" -eq 0 ] && [ "$BE" -eq 0 ] && [ "$VE" -eq 0 ]; then
  echo "✅ 這一包在乾淨 dev 上站得住(而這是必要條件, 不是充分條件 —— 見檔頭)"
  echo "   ⚠️ 射程:本工具跑的是【HEAD + 你這包】。包裡的測試若斷言的性質 HEAD 本來就滿足,"
  echo "      那麼【漏收一支原始檔】不會讓它紅 ——「複製後 dirty 數」只答得出幾支, 答不出哪幾支。"
  exit 0
fi
echo "🔴 這一包在乾淨 dev 上站不住 ⇒ 多半漏收了一支它需要的檔"
exit 1
