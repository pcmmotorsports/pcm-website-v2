#!/bin/sh
# scripts/lib-ledger-drift-strip.sh —— 「帳本 sha 對不上時, 兩份要怎麼比」的【單一來源】
# ============================================================
# 🔴 **為什麼要抽出來**(主視窗 `-f8` 2026-09-06 指示, 逐字「不要再手寫一份等價迴圈」):
#    這條規則原本有兩個地方在用 ——
#      ① `scripts/deploy-order-gate.sh` 的 `comment_only_drift`(⟦db-LEDGERSHADRIFT⟧ 修法丙)
#      ② `scripts/ledger-col2-census.py` 的 ③a/③b 分類
#    而**兩份等價的碼會分岔, 分岔時沒有東西會叫** —— 本 repo 記過太多次。
#
# 🎯 **它做什麼**:從 stdin 讀 SQL, 丟掉【整行都是行註解】的行與空行, 印到 stdout。
#
# 🛑 **它刻意【不碰】兩樣東西**:
#    · **行內的 `--`** —— `'a--b'` 是合法字串常值, 砍它會把語意變更讀成註解漂移
#    · **行尾空白** —— 它可能落在 dollar-quoted 的字串資料裡
#    ⇒ 兩者都往【多擋】的方向偏, 而那是安全的方向。
#
# ⚠️🔴 **已知盲區, 而它往【少擋】偏**:它**分不出那一行在不在字串裡**
#    ⇒ 只動【多行字串常值】內容的改動會被讀成「只有註解不同」。至少兩種:
#      ①以 `--` 開頭的行被當註解丟掉 ②空行 / 純空白行被當空行丟掉。
#    🔬 實測:`printf "SELECT 'a\n\nb';\n"` 與 `printf "SELECT 'a\nb';\n"` 各過一次 ⇒ 兩個 sha 逐字元相同。
#    🛑 要真的關掉這一族得去 lex SQL(引號與 dollar-quote 的狀態機), **不在那一片的體積裡**;
#      主視窗 `-f8` 2026-09-06 接受為**殘餘風險**。`deploy-order-gate-verify` 的 `G` / `H` 兩格在演它,
#      **它們斷言的是【現況】不是【正確】** —— 有人真的去 lex 了, 那兩格會紅。
#
# 用法:  cat x.sql | sh scripts/lib-ledger-drift-strip.sh
grep -vE '^[[:space:]]*(--|$)'
