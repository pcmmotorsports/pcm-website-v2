#!/bin/bash
# run-gate.sh — 跑一道閘, 而**把 rc 與畫面【並排】印出來**。
#
# 用法
#   bash scripts/run-gate.sh <命令…>
#   bash scripts/run-gate.sh --selftest        # 本工具自己的雙向證人
#
# ══════════════════════════════════════════════════════════════════════════════
# 🔴🔴 它為什麼存在 —— 而它【不是】一條規矩(規矩治不好這個)
# ══════════════════════════════════════════════════════════════════════════════
# 2026-09-03 一夜, 同一個人(我)在量閘這件事上壞了兩種尺, **而它們的方向相反**:
#   甲  `cmd | tail -6` ⇒ 管線把 rc 換成 tail 的 ⇒ **畫面說紅, 而 rc 說 0**   (三次)
#   乙  `<(...)` 在 sh 底下 syntax error ⇒ 變數變空 ⇒ **rc 說 0, 而畫面說 syntax error**
#
# 🎯 **共同點不是「忘了收 rc」, 是【一發量測有兩個輸出, 而我每次只挑一個當結論】。**
#    ⇒ 而挑哪一個是**那一發長什麼樣**決定的, 不是我決定的:
#      畫面有紅字 ⇒ 我讀畫面 · 畫面乾淨 ⇒ 我讀 rc
#      ⇒ 📌 **兩種情況我都只讀了會讓我安心的那一個。**
#
# ✅ **所以修法是【兩個都印, 而且並排】** —— 讓「rc=0 而畫面有 syntax error」
#    變成一個**看得見的矛盾**, 而不是兩個各自安心的世界。
#
# 🛑 **而它必須短到我願意手打** —— 那是它做完的驗收條件, 不是風格:
#    memory 記過「修了工具不等於修了我自己的習慣;防護裝進腳本而我下一次是手打的」
#    ⇒ 一支我不會叫的工具, 與沒有這支工具, 對下一次的我印同一個東西。
#    ⇒ 🔬 對照:不用它我要打
#         `cmd > f 2>&1 ; RC=$? ; echo "rc=$RC" ; tail -5 f`(約 45 字元樣板)
#       用它:`bash scripts/run-gate.sh cmd`(約 26 字元)⇒ **更短, 所以我會用。**
#
# ⚠️ **它做不到什麼**(不假裝):
#   · 它**不判斷那道閘對不對** —— 它只讓那一發的兩個輸出同時被看見。
#   · 「矛盾偵測」用的是**字面線索**(下面 SUSPECT)⇒ 它會漏(用別的字報錯的工具)。
#     🔴 而漏的方向是**少報矛盾** ⇒ 少報時它退化成「照樣兩個都印給你」, 不會反過來騙你。
#   · 它不改變被跑的命令的行為;`set -o pipefail` 那類問題請在命令自己那邊解。
#
# 🔴🔴 **它是給【閘】用的 —— 而那不是命名巧合, 是射程**(2026-09-03 第一天就撞到):
#    閘在正常狀態**安靜**;而 `pnpm build` 這種命令**本來就會印一堆 `Error:`**
#    (本機缺 env 的 fallback 實測 85 處 · 加一個 dev-server 共用 `.next` 的警告)
#    ⇒ 拿它跑 build ⇒ **每一次都印「矛盾」** ⇒ 🎯 而每次都叫等於沒叫。
#    ⇒ 📌 **那不是它壞了, 是用錯對象。** 對 build 這種吵的命令, 讀它印的 `rc=` 那一格就好。
#    🛑 而我**沒有**為此把 `Error:` 從 SUSPECT 拿掉 —— 那會讓它對【閘】也變瞎,
#       而閘才是它存在的理由。**縮的是使用範圍, 不是尺。**

set -u
SELF="${BASH_SOURCE[0]}"

# 🔴 這幾個字面是【線索】不是【判準】—— 見上面「做不到什麼」。
#
# 🔴🔴 **而這一行被它自己的第一發真用打過一次, 值得留**:
#    初版含裸的 `FAIL` ⇒ 跑 `deploy-order-gate-verify.sh` 時撞到它印的
#    **`FAIL=0`(那是好消息)** ⇒ 印出一句假的「矛盾」。
#    ⇒ 🎯 **一支剛出生的工具, 第一次真用就誤報。**
#    ⇒ ⇒ 📌 而誤報比漏報致命:**閘死於誤報遠比死於漏報常見, 因為誤報會被主動關掉。**
#    ✅ 修法不是拿掉 `FAIL`, 是**釘住它的形狀**:`FAIL=` 後面接非零、或 `FAIL:` / 行首 `FAIL`。
#    ⚠️ 而這仍然是**字面尺** —— 它會漏(用別的字報錯的工具), 而漏的方向是少報矛盾(退化成兩個都印)。
SUSPECT='syntax error|command not found|Traceback|No such file|Permission denied|🔴|FAIL=[1-9]|FAIL:|^FAIL|Error:'

run_and_report() {
  _log="$(mktemp)" || return 2
  # 🔴 **這一行的形狀是重點**:`cmd > file 2>&1 ; RC=$?`, 中間不准有任何東西。
  #    (`$?` 每一個指令都會覆寫 ⇒ 這是唯一安全的形狀。)
  "$@" > "$_log" 2>&1 ; _rc=$?
  _hits=$(grep -cE "$SUSPECT" "$_log" 2>/dev/null || true)
  printf '\n══ rc=%s ══  (可疑字面 %s 處)\n' "$_rc" "$_hits"
  printf '── 最後 8 行 ──\n'
  tail -8 "$_log"
  # 🎯 這兩句才是這支工具的全部價值:把兩個輸出的【不一致】講出來。
  if [ "$_rc" = 0 ] && [ "${_hits:-0}" -gt 0 ]; then
    printf '\n🔴🔴 矛盾:rc=0(說成功)而畫面有 %s 處可疑字面 —— **不要只讀 rc**。\n' "$_hits"
    printf '   全文:%s\n' "$_log"
  elif [ "$_rc" != 0 ] && [ "${_hits:-0}" = 0 ]; then
    printf '\n🟡 rc=%s(說失敗)而畫面沒有可疑字面 —— 那可能是【被吃掉的輸出】或安靜的失敗。\n' "$_rc"
    printf '   全文:%s\n' "$_log"
  else
    rm -f "$_log"
  fi
  return "$_rc"
}

if [ "${1:-}" = "--selftest" ]; then
  # 🔴 **雙向證人**:一個該綠、一個該紅、一個該印矛盾。
  #    ⚠️ 本 selftest **完全不碰 git** ⇒ 它不需要拋棄式世界, 也就不會撞
  #    `selftest-git-isolation-gate.sh` 那道閘。(那道閘擋的正是「自帶世界卻打到真 repo」。)
  p=0; f=0
  o=$(run_and_report true 2>&1); r=$?
  { [ "$r" = 0 ] && printf '%s' "$o" | grep -q 'rc=0'; } && p=$((p+1)) || { f=$((f+1)); echo "  🔴 該綠那格"; }
  o=$(run_and_report sh -c 'echo boom >&2; exit 3' 2>&1); r=$?
  { [ "$r" = 3 ] && printf '%s' "$o" | grep -q 'rc=3'; } && p=$((p+1)) || { f=$((f+1)); echo "  🔴 該紅那格"; }
  # 🎯 這一格是本工具存在的理由:rc=0 而畫面有錯 ⇒ 必須印「矛盾」
  o=$(run_and_report sh -c 'echo "syntax error near unexpected token"; exit 0' 2>&1); r=$?
  { [ "$r" = 0 ] && printf '%s' "$o" | grep -q '矛盾'; } && p=$((p+1)) || { f=$((f+1)); echo "  🔴 矛盾那格"; }
  # 🔵 負對照:乾淨的成功【不准】印矛盾 —— 否則它每次都叫, 而每次都叫等於沒叫。
  o=$(run_and_report sh -c 'echo all good; exit 0' 2>&1)
  printf '%s' "$o" | grep -q '矛盾' && { f=$((f+1)); echo "  🔴 負對照:乾淨的成功不該印矛盾"; } || p=$((p+1))
  # 🔵 負對照二(2026-09-03 真用抓到):`FAIL=0` 是**好消息**, 不准報矛盾。
  o=$(run_and_report sh -c 'echo "══ 結果:PASS=65 FAIL=0 ══"; exit 0' 2>&1)
  printf '%s' "$o" | grep -q '矛盾' && { f=$((f+1)); echo "  🔴 負對照二:FAIL=0 不該報矛盾"; } || p=$((p+1))
  # 🔴 而正對照要跟著:`FAIL=3` **必須**報矛盾 —— 否則上面那格可以靠「整條規則刪掉」通過。
  o=$(run_and_report sh -c 'echo "══ 結果:PASS=62 FAIL=3 ══"; exit 0' 2>&1)
  printf '%s' "$o" | grep -q '矛盾' && p=$((p+1)) || { f=$((f+1)); echo "  🔴 正對照:FAIL=3 該報矛盾"; }
  echo "── run-gate selftest: $p PASS / $f FAIL"
  [ "$f" = 0 ] || exit 1
  exit 0
fi

[ "$#" -gt 0 ] || { echo "用法: bash $SELF <命令…>  |  bash $SELF --selftest" >&2; exit 2; }
run_and_report "$@"
