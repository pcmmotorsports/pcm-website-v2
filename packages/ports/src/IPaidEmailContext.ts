/**
 * 信上品項表的一列。**欄位是【正面列出】的,不是排除法** ——
 * 這封信寄給客人,多帶一欄就是多一個外洩面(CLAUDE.md Server 端鐵則)。
 *
 * 🔴 **零成本欄**:`price_store` / `price_by_tier` / `cost` / `price_general` 一欄都不在這裡,
 *    而且**不得**以「順手多撈」為由加進來。`AdminOrderDetailItem` 檔頭(`order/types.ts:797`)
 *    對同一組欄位講過同一句話,這裡是它在信件側的同族。
 */
export type PaidEmailLine = {
  /** 品名(`product_snapshot.title`;缺 → `null`,與 `AdminOrderDetailItem.title` 同慣例)。 */
  title: string | null;
  /** 料號(稿上印在品名下方那一行小字;缺 → `null`)。 */
  variantSku: string | null;
  /** 下單數量。 */
  quantity: number;
  /**
   * 這一列的小計 = **下單當下 server 算的 `order_items.line_total`,不重算**。
   * 🔴 重算會讓「信上的數字」與「客人刷的那筆錢」在改價之後分岔,
   *    而分岔的那一封信**寄出去就收不回來**(鐵則 12⑤)。
   */
  lineTotal: MoneyAmount;
};

/**
 * 一封付款成功通知信要印的東西。四個金額欄**對齊 A 版稿的四列**
 * (`email-order-paid-A.html` 小計 / 運費 / 折扣 / 訂單金額)。
 *
 * 🔴 **`linesTruncated` 不是選配。** 讀取端一定有上限,而**少列幾項的信與正常的信長得一模一樣**
 * —— 客人照著清單對,少的那一項他不會知道要問。⇒ 為 `true` 時呼叫端必須 fail-closed(不寄)。
 * 理由全文與同族分析在 `IShippedEmailContext.ts:59-63` 與 backlog `#629`,此處不複製。
 *
 * 🔴 **四個金額的一致性由 DB 保證,不由本型別保證**:
 *    `20260604120000:112` `orders_total_balances`
 *    CHECK (total = subtotal + shipping_fee - discount_total)
 *    ⇒ 呼叫端**不得**自己重算 total 去對帳 —— 重算等於在信件層複製一份會漂的算式。
 */
export type PaidEmailContext = {
  /** 訂單顯示編號(主旨與內文都用它)。 */
  orderDisplayId: string;
  /** 品項表。 */
  lines: PaidEmailLine[];
  /** 🔴 `lines` 沒載完 ⇒ 呼叫端 fail-closed、**不寄**。 */
  linesTruncated: boolean;
  /** 稿上「小計」= `orders.subtotal`(= Σ `line_total`)。 */
  subtotal: MoneyAmount;
  /** 稿上「運費」= `orders.shipping_fee`。 */
  shippingFee: MoneyAmount;
  /**
   * 稿上「折扣」= `orders.discount_total`。
   * 🔴 **正值**(DB `CHECK (discount_total >= 0)`,`20260604120000:103`)——
   *    稿上那個 `−790` 是**排版**不是資料。負號由模板加,不進這裡。
   *    ⚠️ 若讓它帶號,「沒有折扣」與「折扣 0」與「負折扣」會在模板層合成同一個分支。
   */
  discountTotal: MoneyAmount;
  /** 稿上「訂單金額」= `orders.total`。**幣別字樣是模板的靜態標籤,不是這裡的資料。** */
  total: MoneyAmount;
};

