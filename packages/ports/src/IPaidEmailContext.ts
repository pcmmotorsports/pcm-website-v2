/**
 * 🔴 **呼叫端不得寫 `if (result.kind !== 'ok')`**(2026-08-24 codex M3)。
 *
 * 那個寫法**型別上合法**,而它把 `cancelled` 與 `unavailable` **合併成同一個分支** ——
 * 那正好是 Sean 拍板要分開的兩件事:
 * ```
 * cancelled    正常業務動作 ⇒ 不寄、不吵、留一列跳過痕跡
 * unavailable  我們的判斷與資料對不上 ⇒ 不寄、**應該吵**
 * ```
 * ⇒ **請用 `switch (result.kind)` 三個分支寫完**,並在 `default` 放
 *   `const _exhaustive: never = result;` —— 日後再加第四態時,**那一行會紅**。
 *
 * 🔴🔴 **而這一條【關不掉】,我明說,不叫它「窮舉點」**(2026-08-24 codex R2 M2)——
 * ```
 * 測試裡那個 switch 只窮舉了【測試自己的 classify()】
 * ⇒ S4 寫 `if (r.kind !== 'ok')` 仍然完全合法、typecheck 不紅、那格測試也不紅
 * ⇒ 它是一個【測試層的提醒】,不是一道閘。**不要把它當成已經擋住了。**
 * ```
 * **要真的關,唯一有效的形狀是【讓呼叫端物理上無法跳過分支】** ——
 * 例如不直接吐 union,而要求傳入三個 handler(`matchPaidContext(r, { ok, cancelled, unavailable })`)。
 * ⚠️ **而那要在 `packages/ports` 放一個【執行期函式】,而本包目前是 100% 型別**
 *    (量法 `grep -c '^export type \*' packages/ports/src/index.ts` ⇒ 25;
 *     非 type 的 export 行 ⇒ **0**)。
 * ⇒ **那是這個 package 的第一個 runtime 匯出 = 架構決定,不是本片的一行。**
 *   ⇒ **本片刻意不做**,而把它記成 S4 的第一題:**要不要為此開 runtime 匯出。**
 */
export type LoadPaidContextResult =
  /** 撈到了,可以寄。 */
  | { kind: 'ok'; context: PaidEmailContext }
  /**
   * 讀不到、或撈回來的東西對不上(單不存在 / 撈不到 display_id / **這張單 0 項**)。
   * 🔴 呼叫端必須 fail-closed:**不寄、計 error**。這一態**應該**吵。
   * ⚠️ **不得**退化成「就把撈到的印上去」——
   *    一封沒有品項、或金額是 0 的付款確認信,客人看不出是系統壞了還是他被多收了。
   */
  | { kind: 'unavailable' }
