//  ⚠️ **退場一個守門有兩種形狀**:刪掉它 / 把它換成一句永遠成立的話。
//     這裡走的是前者 —— 因為「沒有整段條目」這件事**已經由上面的名單釘住了**,
//     再寫一句「零債」只是同一個宣稱的第二份副本。
//  🔴 **下次有人新增「整段」條目時要把它加回來**:形狀抄
//     `applied-migration-pairing.test.ts` 的「為什麼寫成 `it.fails`」那一段,
//     極性是**內層斷言「觸發條件成立了」**(寫反會變成一個永遠綠的裝飾品,2026-08-23 踩過)。

describe('解析器與字集的自我對照', () => {
  it('正向對照:解析、整段過濾、字集三件都是活的', () => {
    const fake = [
      '//   ① `f_a` **整段**:〔主migration=20260101000000〕 未 apply。',
      '//   ② `f_b` **整段**:〔主migration=20260102000000〕 已 apply。',
      '//   ③ `f_c`(不是整段,應被濾掉)',
    ].join('\n');
    const parsed = parseEntries(fake);
    expect(parsed.map((e) => e.mark)).toEqual(['①', '②', '③']);
    expect(parsed.filter((e) => e.body.includes('**整段**')).map((e) => e.mark)).toEqual(['①', '②']);
    expect(primaryMigration(parsed[0]?.body ?? '')).toEqual(['20260101000000']);
    expect(CLAIM_NOT_APPLIED.some((w) => parsed[0]?.body.includes(w))).toBe(true);
    expect(CLAIM_APPLIED.some((w) => parsed[1]?.body.includes(w))).toBe(true);
  });

  it('不確定性標記:正對照 / 負對照 / 同一行約束 / 日期合法性(2026-08-28 R2 MF4 補)', () => {
    // 🔴 **為什麼這三格在這裡**:在此之前 `UNCERTAIN_ANY_RE` 那段新邏輯在【要 commit 的樹上零覆蓋】——
    //    `EXPECTED_WHOLE_SECTION_MARKS` 今天是 `[]` ⇒ `it.each` 跑 0 格 ⇒ **它整段是死碼**,
    //    而基線逐字印 `Tests 5 passed (5)`。📌 **印 5 passed, 而最重要的迴圈跑 0 次。**
    //    ⇒ 這三格讓新邏輯**在名單仍是 `[]` 時就跑得動** ⇒ **它從此不再是死碼。**
    //    🔴 而修它的人就是當初量到它的人(`-c8` 2026-08-28)—— 把這個閉環寫在這裡,
    //       下一個人才知道這三格為什麼存在。
    const withMark = '//   ① `f` **整段**〔主migration=20260101000000〕〔APPLIED.tsv 無此列〕 未 apply。';
    const withDb = '//   ① `f` **整段**〔主migration=20260101000000〕〔正式庫查過=2026-08-28〕 已 apply。';
    const halfWidth = '//   ① `f` **整段**〔主migration=20260101000000〕(APPLIED.tsv 無此列) 未 apply。';
    const otherLine =
      '//   ① `f` **整段**〔主migration=20260101000000〕 未 apply。\n//      旁白:〔APPLIED.tsv 無此列〕';
    const badDate = '//   ① `f` **整段**〔主migration=20260101000000〕〔正式庫查過=9999-99-99〕 已 apply。';

    // 正對照:尺會叫
    expect(UNCERTAIN_ANY_RE.test(markerLine(withMark)), '正對照:全形〔〕標記應命中').toBe(true);
    expect(checkedDbDateOk(markerLine(withDb)), '正對照:合法日期應通過').toBe(true);
    // 負對照:尺會停 —— 半形括號不是本檔的字面
    expect(UNCERTAIN_ANY_RE.test(markerLine(halfWidth)), '負對照:半形括號不得命中').toBe(false);
    // 🔴 同一行約束(R2 nit):標記寫在條目下方的旁白 ⇒ 不算數
    expect(UNCERTAIN_ANY_RE.test(markerLine(otherLine)), '標記寫在旁白那一行 ⇒ 不得命中').toBe(false);
    //    而它確實出現在 body 裡 —— 這一格證明「同一行」那個收窄真的有作用,不是裝飾
    expect(otherLine.includes('〔APPLIED.tsv 無此列〕'), '前提:那個字面確實在 body 裡').toBe(true);
    // 🔴 日期合法性(R2 nit):9999-99-99 不算數
    expect(checkedDbDateOk(markerLine(badDate)), '負對照:不可能的日期不得通過').toBe(false);
    // 🔴 stripStruck 之後不命中(劃掉的標記不算數)——與上面「刪除線」那格同族
    expect(UNCERTAIN_ANY_RE.test(markerLine(stripStruck(
      '//   ① `f` **整段**〔主migration=20260101000000〕~~〔APPLIED.tsv 無此列〕~~ 未 apply。',
    ))), '劃掉的標記不得命中').toBe(false);
  });

  it('刪除線:留痕的舊句不算宣稱,而【不剝】會誤判成兩邊都命中(負向對照)', () => {
    const struck = '//   ① `f` **整段**:~~〔主migration=20260101000000〕未 apply~~ 更正:它已 apply。';
    const live = stripStruck(struck);
    expect(CLAIM_NOT_APPLIED.some((w) => live.includes(w))).toBe(false);
    expect(CLAIM_APPLIED.some((w) => live.includes(w))).toBe(true);
    expect(CLAIM_NOT_APPLIED.some((w) => struck.includes(w))).toBe(true); // 不剝就會誤判 ⇒ 那一步承重
  });

  it('body 邊界:分節線之後的東西不算進條目(F4;原本吃固定 40 行會誤紅)', () => {
    const src = [
      '//   ① `f` **整段**:〔主migration=20260101000000〕 已 apply。',
      '// ─────────────',
      '// 這一行與 ① 無關,而它含「未套用」三個字',
    ].join('\n');
    const body = parseEntries(src)[0]?.body ?? '';
    expect(body.includes('未套用')).toBe(false);
  });

  it('主錨:同條目裡的旁引編號不得被拿來對帳(F3 的假綠)', () => {
    const body = '//   ① `f` **整段**:〔主migration=20260101000000〕 未 apply(旁引 `20260102000000`)。';
    expect(primaryMigration(body)).toEqual(['20260101000000']);
  });
});
