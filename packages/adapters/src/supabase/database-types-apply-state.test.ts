const UNCERTAIN_ANY_RE = /〔APPLIED\.tsv 無此列〕|〔正式庫查過=(\d{4})-(\d{2})-(\d{2})〕/;
const CHECKED_DB_RE = /〔正式庫查過=(\d{4})-(\d{2})-(\d{2})〕/;
/** 日期合法性:月 01-12、日 01-31(不查大小月 —— 擋的是 `9999-99-99` 那種,不是行事曆)。 */
function checkedDbDateOk(t: string): boolean {
  const m = CHECKED_DB_RE.exec(t);
  if (!m) return false;
  const mo = Number(m[2]);
  const d = Number(m[3]);
  return mo >= 1 && mo <= 12 && d >= 1 && d <= 31;
}
/** 標記必須與 `〔主migration=…〕` **在同一行** —— 否則條目下方的旁白也能餵飽它(R2 nit)。 */
function markerLine(body: string): string {
  const line = body.split('\n').find((l) => /〔主migration=20\d{12}〕/.test(l));
  return line ?? '';
}

