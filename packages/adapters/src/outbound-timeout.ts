// @pcm/adapters — 對外送出(寄信 / 推播)的逾時上界。⟦mail-FETCHTIMEOUT⟧ 2026-09-06

/**
 * 🔴🔴 **對外送出的逾時上界 —— 沒有它, 一個【送完 header 就停住】的伺服器會讓我們永遠等下去。**
 *
 * **病灶**(opus R2 · C2):`fetch` 預設**沒有**逾時 ⇒ `await` 沒有上界
 * ⇒ 平台在 `maxDuration = 60`(`apps/storefront/src/app/api/cron/email-sweep/route.ts:88`)砍掉整個 function
 * ⇒ 那一列留在 `sending`、燒一次 attempt, **而信【可能已經寄出去了】**。
 * 🛑 **時間預算擋不到它, 而理由不是我原本寫的那個**(codex R1 #2 訂正):
 *    ⛔ ~~「`outOfBudget()` 是在認領之前問的」~~ —— **不是**, 它有**五個檢查點**
 *    (`sweep-email-outbox.ts` 的 `1126 / 1173 / 1220 / 1332 / 1665`), 而且**每一發會等的 await
 *    後面都補了一次**(那些註解自陳:「上面那一發 await 可能穿越 deadline」)。
 * ✅ **真正的缺口是【它問的問題】**:那道檢查問的是「**現在**超過預算了嗎」,
 *    而不是「**我接下來這一發最壞會跑多久, 那樣還來得及嗎**」。
 *    ⇒ 📌 **一道只問現在的閘, 對【接下來那一步要花多久】完全失明** ——
 *      而在 send 沒有上界的年代, 那個問題**本來就答不出來**(所以那道閘只能那樣寫)。
 *    ⇒ 🎯 **本常數真正買到的東西**:它讓「接下來那一發最壞多久」**變成一個有限的、寫得出來的數**,
 *      收尾餘裕才能拿它去算(見下方)。
 *
 * 🔬 **10 秒是【算出來的】**(主視窗 2026-09-06 裁 `Q-逾時秒數 = 甲`)——
 *    ⛔ ~~原本我寫的算式是「55 s 預算 ÷ 10 s = 塞得下 5 發」~~ **那個算式是錯的**(codex R1 #1):
 *    一輪的認領上限是 **`CLAIM_LIMIT = 50`**(`email-sweep/route.ts:107`), 不是 5;
 *    而它前面還疊著數段 enqueue。⇒ 🛑 **「一輪塞得下幾發」根本不是這個常數要回答的問題。**
 * ✅ **真正的判準只有一句, 而它與封數無關**:
 * ```
 * 最後一發在「預算耗盡前 1 ms」通過檢查 ⇒ 它最壞會跑滿一整個 timeout ⇒ 然後才落表
 * ⇒ 【收尾餘裕】必須裝得下 (timeout + 落表)
 *    12 s(SEND_TAIL_ALLOWANCE_SECONDS)  ≥  10 s(本常數) + 2 s(markSent)   ✅
 * ⇒ 📌 那一輪會【自己收尾】, 而不是被 kill —— 與一輪寄幾封【無關】。
 * ```
 * 🔴 **而那兩個常數住在不同的套件, 它們之間沒有語言層的關聯** ——
 *    ⇒ 機制補在 `outbound-timeout.test.ts`:它**讀那兩支檔的原始碼**當場算,
 *      任一邊改了而另一邊沒跟上 ⇒ **紅**。🧬 突變驗過:tail 改回 5 ⇒ 1 failed。
 *
 * 🛑🛑 **而它有一個【未量】的前提, 這一句不可以省**:
 *    `email-sweep/route.ts:97` 那句「單封 ~數百 ms」**是一句註解, 不是量測**。
 *    ⇒ **上線後第一天要量的讀數** = `sent_at − claimed_at` 的分佈,
 *      🔴 **而【不可以只量 `sent` 那些列】**(codex R1 #3):被這道逾時判掉的正是**最慢的那些**,
 *      只看 `sent` ⇒ 📌 **倖存者偏差 —— 我砍掉的那一族剛好不會出現在我的樣本裡。**
 *      ✅ 分母要含 `last_error_code = 'network_error'` 的列(用 `claimed_at` 當時間軸)。
 *    ⚠️ **另一個射程**:本 adapter 允許附件到 **40 MiB**(`RESEND_MAX_ATTACHMENTS_BASE64_BYTES`)
 *      ⇒ **小信的 p99 證不到大附件那一族**。今天交易信不帶附件 ⇒ 無實害;
 *      **哪天有人在這條路上掛附件, 這個 10 秒要重算。**
 *    ⇒ 🔴 **p99 若 > 3 s, 這個 10 秒要重談** —— 那時它會開始砍掉**正常**的信,
 *      而那個症狀(信變成 `failed / network_error`)**看起來會像 provider 壞了**。
 *    📌 板列 `⟦mail-FETCHTIMEOUT⟧` 記著這個待量項。
 *
 * 🔵 **做法不是新設計** —— 本 repo 既有前例:`apps/admin/src/lib/shipping/hct-client.ts:235`
 *    逐字 `signal: AbortSignal.timeout(TIMEOUT_MS)`(`:124` = `20_000`)。
 *    ⚠️ **而那支的 20 秒不可以照抄**:它是【人在等畫面】的場景, 本檔是 cron 的批次預算。
 */
export const OUTBOUND_SEND_TIMEOUT_MS = 10_000;
