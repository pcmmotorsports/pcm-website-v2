/**
 * 未稅後綴。**半形 ASCII 括號**(`0x28` / `0x29`), 與板列上 Sean 2026-09-04 拍甲那句逐字相同。
 *
 * ⛔ ~~我第一版註解寫「全形括號」~~ —— **那句與值不符**(codex R1 nit)。
 * 🔬 值從哪來:掃 `docs/launch-todo.md` 的「小計.{0,1}未稅.{0,1}」⇒ **2 處, 兩處都是**
 *    `['0x5c0f','0x8a08','0x28','0x672a','0x7a05','0x29']` ⇒ 半形。
 * 🛑 **全形與半形在畫面上幾乎看不出差別** ⇒ 這一格有測試釘住碼位, 不是靠讀的。
 * 🔴 五個面共用這一份 ⇒ 改它就是五個面一起改, 那正是要的。
 */
export const TAX_EXCLUSIVE_SUFFIX = '(未稅)';

/**
 * 小計那一列該印什麼。
 *
 * @param base 各面自己的基底字面 —— **刻意不寫死** :顧客站詳情頁是「商品小計」,
 *             其餘四面是「小計」。⇒ 🛑 統一成同一個詞是**改文案**, 而那是 Sean 的事、不是本片的。
 * @param taxTotalAmount `orders.tax_total` 原值(整數, 分/元同 `Money.amount`)。
 *
 * 🔴 **判準是 `> 0` 不是 `!== 0`** —— 稅額是非負的, 而若真的出現負數,
 *    那是上游壞了 ⇒ 這裡**不該**把它讀成「有稅」。
 * 🔵 而**三種寫法各自會被哪一格抓到**(codex R1 must-fix 要求寫出來):
 *    · `>= 0` ⇒ 稅 0 那一格紅(它會變成永遠加後綴)
 *    · `!== 0` ⇒ 負數那一格紅(它會把 -1 讀成「有稅」)
 *    ⇒ 📌 **兩格缺一, 就有一種改法溜得過去。**
 */
export function subtotalLabelOf(base: string, taxTotalAmount: number): string {
  return taxTotalAmount > 0 ? `${base}${TAX_EXCLUSIVE_SUFFIX}` : base;
}
