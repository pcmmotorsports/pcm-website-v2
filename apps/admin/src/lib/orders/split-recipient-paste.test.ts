describe('splitRecipientPaste', () => {
  it.each(CASES)('%s', (_label, input, name, phone, address) => {
    expect(splitRecipientPaste(input)).toMatchObject({ name, phone, address, extraPhones: [] });
  });

  it('兩支電話:用第一支, 第二支放進 extraPhones 讓畫面提示', () => {
    expect(splitRecipientPaste('王小明 0912345678 0223456789 台北市中正區忠孝東路一段1號')).toEqual({
      name: '王小明',
      phone: '0912345678',
      address: '台北市中正區忠孝東路一段1號',
      extraPhones: ['0223456789'],
    });
  });

  it('空字串與只有空白:三格都是空的', () => {
    expect(splitRecipientPaste('  \n ')).toEqual({ name: '', phone: '', address: '', extraPhones: [] });
  });
});
