//    admin production 追 dev ⇒ 推 dev 即上線 ⇒ **本旗標不進任何會部署的設定**,
//    dev/本機驗證用 env 開(`REFUND_BACKFILL_UI_ENABLED=1`)。
//
// ⚠️ **刻意不掛 `import 'server-only'`**(理由逐字同隔壁):
//   ① 旗標不是機密, 只是開關;client bundle 誤 import 時非 NEXT_PUBLIC env = undefined
//     ⇒ 恆 false = 入口隱藏 = **fail-closed 方向**, 不存在誤開面。
//   ② 頁層接線測試要真載 page.tsx 量「env → 入口渲染」整條鏈, 掛 server-only 會讓
//     jsdom 頁層測試整族解析失敗 —— 等於用一個裝飾換掉一條真驗證。
export function isRefundBackfillUiEnabled(): boolean {
  return process.env.REFUND_BACKFILL_UI_ENABLED === '1';
}
