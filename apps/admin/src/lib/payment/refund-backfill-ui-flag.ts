//    主視窗 B 2026-09-07 04:2x 裁「B3 = 甲:不接線」⇒ 旗標關時整個區塊**不 render**,
//    開了也只有畫面、按鈕 `disabled`。⇒ 本旗標在片 C 之前**沒有任何一條路會動到資料**。
