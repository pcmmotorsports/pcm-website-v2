import { CARRIER_LABEL } from './carrier-label';

/** `block` = 擋住送出;`warn` = 印出來給人看,但**不擋**(見檔頭的證據強度那段)。 */
export type TrackingIssue = { level: 'block' | 'warn'; message: string };

/**
 * 🔴 兩個警告共用的結尾。**原本寫「新竹那邊會再驗一次」—— 那句是錯的**(R1 MF3):
 * `git grep -niE "hctapiweb|TransData|EDI_WebService" -- apps packages` ⇒ **零命中**,
 * 我們根本沒串 HCT API;而貨號是員工從 HCT 自己的託運單**抄下來**的,
 * 打錯的那一碼只存在我們 DB 裡、**包裹照樣寄達** ⇒ 新竹沒有任何東西可以驗。
 * ⚠️ 那句話會叫員工放心照送,而 `#551` 要修的病(客人查無此件)就走這條路。
 */
const TAIL = '請再核對一次 —— 送出之後沒有人會再幫你抓這個錯。';

/** 貨號 10 碼 = 前 9 碼 + `MOD(前 9 碼, 7)`(`hct-logistics-api-reference.md`,錨點「檢查碼 =」)。 */
function hctCheckDigit(first9: string): number {
  return Number(first9) % 7;
}

/**
 * 這個貨號有沒有問題;`null` = 沒問題(或**我們沒有能力判斷**)。
 *
 * ⚠️ **`null` 有兩種意思,而呼叫端不需要分辨**:「驗過了沒問題」與「這家我們驗不了」。
 *    兩者對**送出**這個動作的結論一樣(放行)⇒ 收成同一個回傳值。
 *    但**理由不一樣**,所以理由寫在這裡而不是靠回傳值表達(見檔頭 `sf` 那段)。
 *
 * 🔴 空字串回 `null`、不回 `block`:**「還沒填」與「填錯了」是兩件事**,
 *    而「非 other 必須有單號」那道已經在 `shipment-dialog.tsx`(錨點 `shipBlocker`)。
 *    在這裡也擋一次 ⇒ 員工會同時看到兩句話講同一件事。
 */
export function trackingNumberIssue(
  carrierCode: string,
  trackingNumber: string,
  /**
   * 🔴 **`false` = 員工還在打字 ⇒ 一律不回問題**(R2 F-A)。
   *
   * ⚠️ **這條的原始理由(逐鍵跳九次「長度不對」)已隨 `Q-C551` 消失** —— 長度規則拿掉了。
   * **但它仍然承重,理由換成量得到的那個**:hct 的貨號打到第 10 個字元時,
   * 中間狀態很可能是一個檢查碼不符的 10 位數 ⇒ **人還在打,警告先閃一次**。
   * ⇒ 在**打字中**出現、又在打完後消失的警告,會訓練員工「那行字是雜訊」——
   *   而它與「非 other 必須有單號」共用同一個位置,**會一起被無視**。
   * ⇒ 呼叫端用 `onBlur`(離開欄位)把它切成 `true`。
   */
  settled = true,
): TrackingIssue | null {
  const t = trackingNumber.trim();
  if (t === '') return null;
  if (!settled) return null;

  // 🔴🔴 **上限 39 —— 這是【全部貨運商】共用的唯一一條長度規則。**
  //    **來源:Sean 2026-08-16 口述,逐字「我們每一家貨運都不一樣,不限制多少數字或者號碼,
  //    最長 39位數」。⚠️【未見書面來源】** —— 他是老闆權威,但**權威不等於已查證**,
  //    引用這個 39 的人要把兩者分開講(三來源律:這是來源①口述,不是②官方文件)。
  //
  // 🔴🔴 **本檔曾經有一條「長度必須 = 10」,那條【已被 Sean 的事實推翻,不是降級】。**
  //    它來自那份自己標著「版本未確認」的 HCT PDF,而 Sean 說每家不一樣。
  //    ⚠️ **注意我原本寫的理由是錯的**:舊 code 的長度檢查在 hct 早退【之後】,對 sf 根本不會觸發
  //       ⇒ 「留著會對 sf 噪音誤報」**不成立**。結論(該拿掉)對,但別照那個理由決定要不要重看。
  //    ⇒ 真正的理由:它對 **hct 自己** 就會誤報(每家不一樣 = hct 也未必永遠 10 碼),
  //      而**噪音警告的下場是被無視** ——
  //      那比沒有更糟:它會連帶讓【真正的】警告一起失效。
  //    ⚠️ **不要因為「PDF 上寫 10 碼」就把它加回來。** 要加,先拿真託運單對過。
  // 🔴 **這一段【刻意排在 hct 早退之前】**:上限是全部貨運商共用的,
  //    放到早退之後 ⇒ sf / other / 未知碼的 40 位會整個漏掉。守門在 test 的「39/40 正負對照」那格。
  if (t.length > 39) {
    return {
      level: 'warn',
      message: `貨運單號最長 39 位,這個是 ${t.length} 位。${TAIL}`,
    };
  }

  // 以下只對 hct。`sf` = 規則未查證(不是豁免)、`other` = 本來就沒有貨號。
  if (carrierCode !== 'hct') return null;

  // 🔴 檢查碼只在**恰好 10 位純數字**時才驗 —— 那條規則的前提就是 10 碼
  //    (`hct-logistics-api-reference.md` 錨點「檢查碼 =」)。
  //    ⚠️ **不是 10 位就【不出意見】**,不是「報錯」—— 長度已經不歸我們管了(見上)。
  if (!/^\d{10}$/.test(t)) return null;

  const expected = hctCheckDigit(t.slice(0, 9));
  if (Number(t[9]) !== expected) {
    return {
      level: 'warn',
      message: `${CARRIER_LABEL.hct}貨號的檢查碼對不上(第 10 碼照規則應該是 ${expected})。${TAIL}`,
    };
  }
  return null;
}
