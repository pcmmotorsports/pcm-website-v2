/** 🔴🔴 **Sean 2026-09-03 拍 `Q15 = 甲`(改)** —— 而本片做的是**結構**不是**字**。
 *
 *  ## 為什麼上面那個常數還留著
 *  它是 `CART_LINES_INVALID_MESSAGE` 的來源(server 那條路),而 server 那句涵蓋
 *  quantity / 空車 / >200 列**四類成因**,對它們具體的指示是錯的 ⇒ **不能一起改**。
 *  📌 **共用的是字面, 不是成因** —— 這一格是同檔 `:47-52` 早就寫過的,本片沒有推翻它。
 *
 *  ## 這支函式解掉的是【擋下前一次修法的那兩個理由裡的第一個】
 *  `checkout-messages.ts` 上方逐字記著 codex R3 + Fable 兩輪各判一次:
 *  ```
 *  ① 訊息說「那件商品」而【沒有指名是哪一件】, 而 CartView 對零變體那一列不渲染任何標記
 *     ⇒ 它與正常列長得一模一樣 ⇒ 客人只能猜著刪 ⇒ 刪掉他本來要買的那件而不自知
 *  ② 「移除」= 叫他放棄一件他本來想買的東西 ⇒ 產品決定, 不是文案潤稿
 *  ```
 *  ✅ **①【本片解掉】**:訊息現在**吃品名**,叫得出是哪一件。
 *  🛑 **②【本片不碰】**:字面刻意維持「回購物車確認」這種**中性動詞**,**沒有**叫他移除 ——
 *     那個動詞是 Sean 的板。**⇒ 這支函式讓那句話【有能力】指名, 而不替他決定要叫客人做什麼。**
 *
 *  ## 🛑 它今天【客人看不到】—— 這一格不要被讀成「已修好客人看到的話」
 *  本檔末尾那段記著:這道 guard 要「一支**上架中**的零變體商品」才 fire,而今天 **0 支**
 *  ⇒ **驗收只能靠單元測試 + 突變, 不能靠「去正式站走一次」**(兩個世界會印同一個畫面)。
 *
 *  @param names 那幾列的品名(已解析、**原順序、不去重**)。**空陣列 = 叫不出名字** ⇒ 退回不指名的版本。
 *  🔴 **「不去重」是刻意的**(codex nit):同 `productId` 無變體在 `addItem` 就已併成一列
 *     ⇒ 去重唯一會 fire 的世界是【同名不同件】, 而那正是它會做錯事的世界。
 *     ⇒ 📌 **不要「順手」把 `new Set` 加回來** —— 那是已經被否決過的行為。
 */
export function cartLineMissingVariantMessage(names: readonly string[]): string {
  // 🔴 出路那一半 —— **字面沿用站上既有的**, 不自創:
  //    `charge-actions.ts:87/90/91` 三處 + `ProductInfo.tsx:214` 都是「**聯繫客服 LINE**」,
  //    而 `ProductInfo.tsx:211` 逐字寫著「沿用既有字面(付款那條路四處都這樣寫)」。
  //    ⛔ ~~我第一版寫「請到『商店據點』頁聯絡客服」~~ —— 那是**我自創的第五種說法**,
  //       而站上同一條路(結帳)已經有一種。📌 **抄站上既有的用法, 不要自創。**
  //    🛑 **這裡是純字串**(`ChargeState.message: string` 一路傳到渲染端)⇒ **給不了可以點的連結**。
  //       要變成可點的, 得把 `message` 從 `string` 改成 ReactNode 並動整條 payment-error
  //       生命週期(`usePaymentErrors` / `ChargeState` 六態)⇒ **那是另一片, 而且碰金流。**
  const exit = '如果不確定是哪一件,請聯繫客服 LINE。';
  if (names.length === 0) {
    // 叫不出名字時**不要假裝叫得出** —— 這一支的價值在指名, 而指不出來時要退回誠實的版本。
    return `${CART_LINE_MISSING_VARIANT_MESSAGE}。${exit}`;
  }
  // 🔵 多列時全部列出, 不截斷:截斷會讓客人以為只有那幾件, 而他要處理的是全部。
  // 🔵 單複數與標點(codex nit):複數走「這 N 件」——`${n} 件`前後各留一個空格,
  //    避免「這2 件」那種擠在一起的長相;冒號改成全形, 與同句其餘標點一致。
  const count = names.length === 1 ? '這件' : `這 ${names.length} 件`;
  const back = names.length === 1 ? '這件' : '這幾件';
  return `購物車裡${count}商品缺少規格資訊,無法結帳:${names.join('、')}。請回購物車確認${back}商品。${exit}`;
}

