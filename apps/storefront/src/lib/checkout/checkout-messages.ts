// checkout-messages — 結帳路徑上【客人看得到的話】,而它們住在兩個以上的呼叫端。
//
// ══ 為什麼有這一支(2026-09-02,⟦b4-NOVARIANT-CHECKOUTMSG⟧)═══════════════════
// 🔴 「購物車有商品缺少規格資訊」那一句**同時寫在兩個地方**:
//      · `hooks/useChargePayment.tsx`      —— client 端送出前那道
//      · `app/checkout/charge-actions.ts`  —— server action 那道
//    ⇒ 📌 **而板上那一列只點名了前者。**
//    ⇒ ⇒ 只改被點名的那一處 ⇒ 另一條路照樣把客人送去做那件做不到的事,
//       **而三綠不會紅、diff 上看起來這一件已經修好了。**
//    ✅ 所以先把它變成【一個字面】,再改它。**下一個人改這句話時不必先找到兩個地方。**
//
// ══ 🔴 那一句原本錯在哪(不是措辭,是它叫人做一件做不到的事)═══════════════════
//    ⛔ 舊字面:「購物車有商品缺少規格資訊,**請返回購物車重新確認**」
//    ⇒ 那支商品**本來就沒有規格可選** ⇒ 購物車上**沒有東西可以「確認」** ⇒ 客人卡死。
//    ✅ 而他做得到的動作是【移除】—— `components/CartView.tsx` 那顆鈕的字面就是「移除」
//       ⇒ 訊息裡用**同一個詞**,他才找得到那顆鈕。
//
// ══ 🔴 而它少了一句,而那一句今晚是全站的規矩 ═════════════════════════════════
//    這句話出現在客人**填完卡號、按下確認付款【之後】** ⇒ 他一定會想「我的卡被扣了嗎」。
//    ✅ 兩個呼叫端都在**任何付款動作之前**就 return(client 端在 `setState('submitting')` 之前;
//       server 端在 ②b 驗證段、`TapPayPrimeInput` 都還沒 parse)⇒ **「這一次沒有送出付款請求」成立。**
//    ⛔ ~~我第一版寫「您沒有被扣款」~~ **那句過度絕對**(codex R1 must-fix):
//       `CheckoutView.tsx:211` 的 `confirmProceedIfInflight()` **允許客人在另一筆付款可能還在進行時繼續**
//       ⇒ 那一筆可能在本次 `getPrime()` 等待期間完成扣款 ⇒ **他的卡真的被扣了, 而我們照樣印那句話。**
//       📌 **⇒ 「這一次沒有送出」是關於【這一次】的事實;「您沒有被扣款」是關於【那張卡】的宣稱。**
//       **⇒ ⇒ 我們答得出前者, 答不出後者。**
//    🛑 而這一格**不得複製到別處**:`checkout/callback/page.tsx` 那幾句刻意**不斷言**扣款與否
//       (`:53` 逐字「不斷言已收款」)—— 因為那時錢**可能**動了。
//    ⇒ 📌 **同一種句子,在兩個地方一個是誠實一個是說謊 —— 差別只在它站在付款動作的哪一邊。**

