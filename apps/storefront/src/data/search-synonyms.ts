/**
 * 查一個詞的正式名。查不到回 `null`。
 *
 * 🔵 **完全比對**(折過之後),不做前綴 —— 俗稱是一個**整個詞**,
 *    前綴會讓「油」命中「油箱貼」而那不是同義,是誤觸。
 */
export function synonymFor(term: string, fold: (s: string) => string): SearchSynonym | null {
  const f = fold(term);
  if (f === '') return null;
  return SEARCH_SYNONYMS.find((s) => fold(s.from) === f) ?? null;
}
