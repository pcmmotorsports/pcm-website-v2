/** 對到哪一種 facet。🔵 `category` 目前是**名稱**比對(對齊 `?category=<名稱>`)。 */
export type SynonymKind = 'category' | 'brand' | 'vehicle';

export type SearchSynonym = {
  /** 客人打的字(俗稱)。 */
  readonly from: string;
  /** 目錄裡的正式名 —— 🔴 必須與 taxonomy 裡的字**逐字相同**,否則對不上。 */
  readonly to: string;
  readonly kind: SynonymKind;
  /** 這一列是誰說的。 */
  readonly source: 'sean' | 'verified' | 'draft';
  /** 加進來的日期(YYYY-MM-DD)。🔴 沒有它就數不出 draft 躺多久。 */
  readonly added: string;
  /** 怎麼來的 / 怎麼證的。`draft` 的**必填**。 */
  readonly note: string;
};

